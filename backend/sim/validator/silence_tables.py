# AMR-NB FT0..7 (참고/2차)
SILENCE_AMR: dict[int, bytes] = {
    0: bytes([0x04, 0x63, 0x3C, 0xC7, 0xF0, 0x63, 0x04, 0x39, 0xFF, 0xE0, 0x00, 0x00, 0x00]),
    1: bytes([0x0C, 0xC6, 0x3C, 0xC7, 0xFF, 0xF0, 0xF7, 0xB7, 0xEF, 0x7F, 0x3E, 0x00, 0xE6, 0x06]),
}


def write_mute(count: int, *, wb: bool = True, mode: int = 8) -> bytes:
    """count 개의 묵음 packet byte 열."""
    table = SILENCE_AMRWB if wb else SILENCE_AMR
    if mode not in table:
        raise KeyError(f"mode {mode} 의 묵음 패킷 표 없음")
    return table[mode] * max(0, count)
